// Package connections manages saved connection profiles (without secrets),
// their credentials and the live sessions opened from them.
package connections

import (
	"crypto/rand"
	"fmt"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
	"time"

	"dbstudio/internal/apperr"
	"dbstudio/internal/config"
	"dbstudio/internal/database"
	"dbstudio/internal/sqllex"
	"dbstudio/internal/sshtunnel"
)

// Environment classifies a connection to reduce the risk of running SQL in
// the wrong place.
type Environment string

const (
	EnvLocal       Environment = "local"
	EnvDevelopment Environment = "development"
	EnvStaging     Environment = "staging"
	EnvProduction  Environment = "production"
)

// Profile is a saved connection. It never contains a password.
type Profile struct {
	ID                      string              `json:"id"`
	Name                    string              `json:"name"`
	Kind                    database.Kind       `json:"kind"`
	Host                    string              `json:"host"`
	Port                    int                 `json:"port"`
	User                    string              `json:"user"`
	Database                string              `json:"database"`
	TLS                     database.TLSOptions `json:"tls"`
	Params                  map[string]string   `json:"params"`
	AllowCleartextPasswords bool                `json:"allowCleartextPasswords"`
	Environment             Environment         `json:"environment"`
	Color                   string              `json:"color"`
	ReadOnly                bool                `json:"readOnly"`
	// SavePassword asks to keep the password in the OS keyring.
	SavePassword          bool `json:"savePassword"`
	ConnectTimeoutSeconds int  `json:"connectTimeoutSeconds"`

	// Socket is a Unix socket path used instead of host:port.
	Socket string `json:"socket"`
	// SSH reaches the server through an SSH tunnel.
	SSH SSHOptions `json:"ssh"`
	// InitSQL runs on every new physical connection (HeidiSQL "startup
	// script"), statements separated by semicolons.
	InitSQL string `json:"initSQL"`
	// KeepAliveSeconds pings the server periodically (0 = off).
	KeepAliveSeconds int `json:"keepAliveSeconds"`
	// Folder groups profiles in the tree ("A/B" nests); "" = top level.
	Folder  string `json:"folder"`
	Comment string `json:"comment"`
	// DatabaseFilter limits the databases listed in the tree: names or
	// patterns with * and ?, separated by ";" ("" = all).
	DatabaseFilter string `json:"databaseFilter"`
	// Stats is maintained by the application (never taken from the UI).
	Stats     ConnStats `json:"stats"`
	CreatedAt time.Time `json:"createdAt"`
	UpdatedAt time.Time `json:"updatedAt"`
}

// SSHOptions configures the SSH tunnel. The password or key passphrase is a
// secret kept like the database password (keyring when SaveSecret).
type SSHOptions struct {
	Enabled    bool   `json:"enabled"`
	Host       string `json:"host"`
	Port       int    `json:"port"`
	User       string `json:"user"`
	Auth       string `json:"auth"` // password | key | agent
	KeyFile    string `json:"keyFile"`
	SaveSecret bool   `json:"saveSecret"`
}

// ConnStats counts connections (HeidiSQL session statistics).
type ConnStats struct {
	Connects        int       `json:"connects"`
	Failures        int       `json:"failures"`
	LastConnectedAt time.Time `json:"lastConnectedAt"`
}

// InitStatements splits InitSQL into statements.
func (p Profile) InitStatements() []string {
	var out []string
	for _, st := range sqllex.Split(p.InitSQL) {
		if t := strings.TrimSpace(st.Text); t != "" {
			out = append(out, t)
		}
	}
	return out
}

// TunnelConfig converts the SSH options (secret filled by the caller).
func (p Profile) TunnelConfig(secret string) sshtunnel.Config {
	return sshtunnel.Config{Host: p.SSH.Host, Port: p.SSH.Port, User: p.SSH.User, Auth: p.SSH.Auth, KeyFile: p.SSH.KeyFile, Secret: secret,
		Timeout: time.Duration(p.ConnectTimeoutSeconds) * time.Second}
}

// ConnectParams converts the profile into driver parameters.
func (p Profile) ConnectParams(password string) database.ConnectParams {
	t := time.Duration(p.ConnectTimeoutSeconds) * time.Second
	if t <= 0 {
		t = 10 * time.Second
	}
	return database.ConnectParams{
		Kind:                    p.Kind,
		Host:                    p.Host,
		Port:                    p.Port,
		User:                    p.User,
		Password:                password,
		Database:                p.Database,
		TLS:                     p.TLS,
		Params:                  p.Params,
		AllowCleartextPasswords: p.AllowCleartextPasswords,
		ConnectTimeout:          t,
		Socket:                  p.Socket,
		InitSQL:                 p.InitStatements(),
	}
}

var idRe = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)

// ValidID reports whether s looks like a profile id generated by NewID.
func ValidID(s string) bool { return idRe.MatchString(s) }

// NewID returns a random UUIDv4.
func NewID() string {
	var b [16]byte
	_, _ = rand.Read(b[:])
	b[6] = (b[6] & 0x0f) | 0x40
	b[8] = (b[8] & 0x3f) | 0x80
	return fmt.Sprintf("%x-%x-%x-%x-%x", b[0:4], b[4:6], b[6:8], b[8:10], b[10:16])
}

var colorRe = regexp.MustCompile(`^#[0-9a-fA-F]{6}$`)

// Normalize trims fields and fills defaults; Validate must be called after.
func (p Profile) Normalize() Profile {
	p.Name = strings.TrimSpace(p.Name)
	p.Host = strings.TrimSpace(p.Host)
	p.User = strings.TrimSpace(p.User)
	p.Database = strings.TrimSpace(p.Database)
	if p.Kind == "" {
		p.Kind = database.MySQL
	}
	if p.Port == 0 {
		p.Port = 3306
	}
	if p.TLS.Mode == "" {
		p.TLS.Mode = database.TLSPreferred
	}
	if p.Environment == "" {
		p.Environment = EnvDevelopment
	}
	if p.Params == nil {
		p.Params = map[string]string{}
	}
	clean := map[string]string{}
	for k, v := range p.Params {
		k = strings.TrimSpace(k)
		if k != "" {
			clean[k] = strings.TrimSpace(v)
		}
	}
	p.Params = clean
	if !colorRe.MatchString(p.Color) {
		p.Color = ""
	}
	if p.ConnectTimeoutSeconds <= 0 || p.ConnectTimeoutSeconds > 300 {
		p.ConnectTimeoutSeconds = 10
	}
	p.Socket = strings.TrimSpace(p.Socket)
	p.SSH.Host = strings.TrimSpace(p.SSH.Host)
	p.SSH.User = strings.TrimSpace(p.SSH.User)
	p.SSH.KeyFile = strings.TrimSpace(p.SSH.KeyFile)
	if p.SSH.Port == 0 {
		p.SSH.Port = 22
	}
	if p.SSH.Auth == "" {
		p.SSH.Auth = sshtunnel.AuthPassword
	}
	if p.SSH.Auth == sshtunnel.AuthAgent {
		p.SSH.SaveSecret = false
	}
	if p.KeepAliveSeconds < 0 {
		p.KeepAliveSeconds = 0
	}
	if p.KeepAliveSeconds > 0 && p.KeepAliveSeconds < 5 {
		p.KeepAliveSeconds = 5
	}
	// Folders: trimmed segments joined by "/".
	var segs []string
	for _, f := range strings.Split(p.Folder, "/") {
		if f = strings.TrimSpace(f); f != "" {
			segs = append(segs, f)
		}
	}
	p.Folder = strings.Join(segs, "/")
	p.Comment = strings.TrimSpace(p.Comment)
	p.DatabaseFilter = strings.TrimSpace(p.DatabaseFilter)
	return p
}

// Validate checks profile fields that do not depend on the driver.
func (p Profile) Validate() error {
	var problems []string
	if p.Name == "" {
		problems = append(problems, "o nome da conexão é obrigatório")
	}
	if len(p.Name) > 100 {
		problems = append(problems, "o nome da conexão deve ter no máximo 100 caracteres")
	}
	switch p.Environment {
	case EnvLocal, EnvDevelopment, EnvStaging, EnvProduction:
	default:
		problems = append(problems, "ambiente inválido")
	}
	if p.SSH.Enabled {
		if p.Socket != "" {
			problems = append(problems, "socket Unix e túnel SSH não podem ser usados juntos")
		}
		if err := p.TunnelConfig("").Validate(); err != nil {
			problems = append(problems, err.Error())
		}
	}
	if len(p.Folder) > 200 || len(p.Comment) > 2000 || len(p.DatabaseFilter) > 2000 || len(p.InitSQL) > 64*1024 {
		problems = append(problems, "pasta, comentário, filtro ou script inicial grandes demais")
	}
	if p.KeepAliveSeconds > 3600 {
		problems = append(problems, "o keep-alive deve ser de no máximo 3600 segundos")
	}
	for _, st := range p.InitStatements() {
		cat, _, _ := sqllex.Classify(st)
		switch {
		case cat == sqllex.CatTransaction:
			problems = append(problems, "o script inicial não pode controlar transações")
		case p.ReadOnly && cat != sqllex.CatRead && cat != sqllex.CatSession:
			problems = append(problems, "em conexões somente leitura o script inicial só aceita leitura e SET")
		}
	}
	if len(problems) > 0 {
		return apperr.New(apperr.CodeValidation, strings.Join(problems, "; "))
	}
	return nil
}

// ProfilesVersion is the schema version of connections.json.
const ProfilesVersion = 1

type profilesFile struct {
	Profiles []Profile `json:"profiles"`
}

// ProfileStore persists profiles in connections.json, keeping their order.
type ProfileStore struct {
	mu       sync.RWMutex
	path     string
	profiles []Profile
}

// OpenProfileStore loads profiles from dir. A load error is returned with a
// usable empty store.
func OpenProfileStore(dir string) (*ProfileStore, error) {
	s := &ProfileStore{path: filepath.Join(dir, "connections.json")}
	f, ok, err := config.Load[profilesFile](s.path, ProfilesVersion)
	if ok {
		for _, p := range f.Profiles {
			if ValidID(p.ID) {
				s.profiles = append(s.profiles, p.Normalize())
			}
		}
	}
	return s, err
}

func (s *ProfileStore) saveLocked() error {
	return config.Save(s.path, ProfilesVersion, profilesFile{Profiles: s.profiles})
}

// List returns profiles in user order.
func (s *ProfileStore) List() []Profile {
	s.mu.RLock()
	defer s.mu.RUnlock()
	out := make([]Profile, len(s.profiles))
	copy(out, s.profiles)
	return out
}

// Get returns one profile.
func (s *ProfileStore) Get(id string) (Profile, error) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	for _, p := range s.profiles {
		if p.ID == id {
			return p, nil
		}
	}
	return Profile{}, apperr.New(apperr.CodeNotFound, "conexão não encontrada")
}

// Put inserts or updates a profile and persists the file.
func (s *ProfileStore) Put(p Profile) (Profile, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	now := time.Now().UTC()
	prev := append([]Profile(nil), s.profiles...)
	found := false
	for i := range s.profiles {
		if s.profiles[i].ID == p.ID {
			p.CreatedAt = s.profiles[i].CreatedAt
			p.Stats = s.profiles[i].Stats
			p.UpdatedAt = now
			s.profiles[i] = p
			found = true
			break
		}
	}
	if !found {
		p.CreatedAt, p.UpdatedAt = now, now
		s.profiles = append(s.profiles, p)
	}
	if err := s.saveLocked(); err != nil {
		s.profiles = prev
		return Profile{}, err
	}
	return p, nil
}

// RecordConnect updates the connection statistics of a profile.
func (s *ProfileStore) RecordConnect(id string, ok bool) {
	s.mu.Lock()
	defer s.mu.Unlock()
	for i := range s.profiles {
		if s.profiles[i].ID == id {
			if ok {
				s.profiles[i].Stats.Connects++
				s.profiles[i].Stats.LastConnectedAt = time.Now().UTC()
			} else {
				s.profiles[i].Stats.Failures++
			}
			_ = s.saveLocked()
			return
		}
	}
}

// Delete removes a profile.
func (s *ProfileStore) Delete(id string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	prev := append([]Profile(nil), s.profiles...)
	out := s.profiles[:0:0]
	for _, p := range s.profiles {
		if p.ID != id {
			out = append(out, p)
		}
	}
	if len(out) == len(prev) {
		return apperr.New(apperr.CodeNotFound, "conexão não encontrada")
	}
	s.profiles = out
	if err := s.saveLocked(); err != nil {
		s.profiles = prev
		return err
	}
	return nil
}

// Reorder sets the order of profiles. Unknown ids are ignored and missing
// ones are kept at the end in their current order.
func (s *ProfileStore) Reorder(ids []string) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	prev := append([]Profile(nil), s.profiles...)
	byID := map[string]Profile{}
	for _, p := range s.profiles {
		byID[p.ID] = p
	}
	var out []Profile
	for _, id := range ids {
		if p, ok := byID[id]; ok {
			out = append(out, p)
			delete(byID, id)
		}
	}
	for _, p := range prev {
		if _, ok := byID[p.ID]; ok {
			out = append(out, p)
		}
	}
	s.profiles = out
	if err := s.saveLocked(); err != nil {
		s.profiles = prev
		return err
	}
	return nil
}
