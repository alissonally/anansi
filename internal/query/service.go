// Package query executes SQL for editor tabs.
//
// Model:
//   - a connections.Session owns one connection pool per saved profile;
//   - each editor tab that executes SQL pins one physical connection from that
//     pool (a tabContext), so session state such as USE, SET @var and open
//     transactions behaves as in a terminal client;
//   - every run is an execution with its own cancel function;
//   - large result sets are read page by page through a cursor that stays
//     open on the tab's connection until it is exhausted, replaced or idle.
package query

import (
	"context"
	"crypto/rand"
	"database/sql"
	"encoding/hex"
	"errors"
	"strings"
	"sync"
	"time"

	"dbstudio/internal/apperr"
	"dbstudio/internal/connections"
	"dbstudio/internal/database"
	"dbstudio/internal/sqllex"
)

// Sessions is the subset of connections.Manager used here.
type Sessions interface {
	Get(id string) (*connections.Session, error)
	OnClose(fn func(id string))
}

// Options are read before every execution.
type Options struct {
	PageSize           int
	Timeout            time.Duration // 0 = none
	ConfirmDestructive bool
	// Warnings reads SHOW WARNINGS after each statement (first
	// maxWarningStatements of a script).
	Warnings bool
}

// maxWarningStatements bounds the extra SHOW WARNINGS round trips of a script.
const maxWarningStatements = 200

// Hooks receive notifications after executions.
type Hooks struct {
	// AfterStatement is called for every executed statement.
	AfterStatement func(ev StatementEvent)
}

// StatementEvent describes one executed statement (for history and metadata
// cache invalidation).
type StatementEvent struct {
	ConnectionID string
	Database     string
	SQL          string
	Kind         sqllex.Category
	Duration     time.Duration
	Err          *database.DBError
	RowCount     int64
	At           time.Time
	// Source is SourceEditor, SourceData or SourceApp.
	Source string
}

// Limits.
const (
	// MaxCursorRows caps how many rows a single result may load in total.
	MaxCursorRows = 200_000
	// CursorIdleTimeout closes cursors that were not read for a while.
	CursorIdleTimeout = 15 * time.Minute
	// ConnIdleTimeout releases a tab's pinned connection when idle (and not
	// in a transaction).
	ConnIdleTimeout = 20 * time.Minute
	cancelGrace     = 3 * time.Second
	acquireTimeout  = 15 * time.Second
)

// Service runs SQL for tabs.
type Service struct {
	sessions Sessions
	options  func() Options
	hooks    Hooks

	mu   sync.Mutex
	tabs map[string]*tabContext

	browseMu sync.Mutex
	browses  map[string]*browsing

	stop chan struct{}
	wg   sync.WaitGroup
}

// tabContext is the execution context of one editor tab.
type tabContext struct {
	id string
	// busy serialises executions and fetches on the tab (TryLock => busy).
	busy sync.Mutex

	// mu guards the fields below. It is never held during network I/O.
	mu        sync.Mutex
	sessionID string
	sess      *connections.Session
	conn      *sql.Conn
	connID    int64
	database  string
	inTx      bool
	// hadWarnings: the last statement left warnings in the diagnostics area.
	hadWarnings bool
	cursor      *cursor
	running     *execution
	lastUsed    time.Time
}

type execution struct {
	id        string
	cancel    context.CancelFunc
	once      sync.Once
	cancelled bool
	mu        sync.Mutex
}

func (e *execution) markCancelled() bool {
	e.mu.Lock()
	defer e.mu.Unlock()
	was := e.cancelled
	e.cancelled = true
	return !was
}

func (e *execution) isCancelled() bool {
	e.mu.Lock()
	defer e.mu.Unlock()
	return e.cancelled
}

// NewService creates the query service.
func NewService(sessions Sessions, options func() Options, hooks Hooks) *Service {
	s := &Service{sessions: sessions, options: options, hooks: hooks, tabs: map[string]*tabContext{}, stop: make(chan struct{})}
	sessions.OnClose(s.releaseSession)
	s.wg.Add(1)
	go s.janitor()
	return s
}

func newID() string {
	var b [12]byte
	_, _ = rand.Read(b[:])
	return hex.EncodeToString(b[:])
}

// ValidTabID accepts the ids generated by the frontend (UUIDs or similar).
func ValidTabID(id string) bool {
	if len(id) < 8 || len(id) > 64 {
		return false
	}
	for _, r := range id {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_') {
			return false
		}
	}
	return true
}

func (s *Service) tab(id string, create bool) (*tabContext, error) {
	if !ValidTabID(id) {
		return nil, apperr.New(apperr.CodeValidation, "identificador de aba inválido")
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	t, ok := s.tabs[id]
	if !ok {
		if !create {
			return nil, nil
		}
		t = &tabContext{id: id, lastUsed: time.Now()}
		s.tabs[id] = t
	}
	return t, nil
}

// ExecuteRequest asks to run SQL in a tab.
type ExecuteRequest struct {
	TabID        string `json:"tabId"`
	ConnectionID string `json:"connectionId"`
	// SQL is the text to consider: the whole editor content or the selection.
	SQL string `json:"sql"`
	// CursorOffset (byte offset in SQL) selects the statement under the
	// cursor in "statement" mode; -1 runs all statements in SQL.
	CursorOffset int `json:"cursorOffset"`
	// Mode: "statement" (one statement; result is paged with a cursor) or
	// "script" (every statement sequentially, stop on first error).
	Mode string `json:"mode"`
	// Database to select before running (the tab's default schema), "" to
	// keep the current one.
	Database string `json:"database"`
	// Confirmed acknowledges a previous confirmation_required response.
	Confirmed bool `json:"confirmed"`
	// Source is "editor" (default) or "data" (table data grid); data
	// browsing is not written to the query history.
	Source string `json:"source,omitempty"`
	// Profile collects the server profile of the statements (an extra
	// result is appended). Large results are not paged in this mode.
	Profile bool `json:"profile,omitempty"`
}

// StatementResult is the outcome of one statement.
type StatementResult struct {
	Index          int                `json:"index"`
	SQL            string             `json:"sql"`
	Line           int                `json:"line"` // 1-based line within the request SQL
	Kind           sqllex.Category    `json:"kind"`
	Columns        []Column           `json:"columns"`
	Rows           [][]any            `json:"rows"`
	HasRows        bool               `json:"hasRows"`
	HasMore        bool               `json:"hasMore"`
	LimitReached   bool               `json:"limitReached"`
	CursorID       string             `json:"cursorId,omitempty"`
	TruncatedCells [][2]int           `json:"truncatedCells,omitempty"`
	RowsAffected   *int64             `json:"rowsAffected,omitempty"`
	LastInsertID   *int64             `json:"lastInsertId,omitempty"`
	DurationMs     float64            `json:"durationMs"`
	Error          *database.DBError  `json:"error,omitempty"`
	Warnings       []database.Warning `json:"warnings,omitempty"`
	// Profile marks the extra result with the statement profile.
	Profile bool `json:"profile,omitempty"`
}

// ExecuteResponse is returned by Execute.
type ExecuteResponse struct {
	ExecutionID   string            `json:"executionId"`
	Results       []StatementResult `json:"results"`
	Database      string            `json:"database"`
	InTransaction bool              `json:"inTransaction"`
	Cancelled     bool              `json:"cancelled"`
	DurationMs    float64           `json:"durationMs"`
	// Notice reports side effects such as a lost connection.
	Notice string `json:"notice,omitempty"`
}

// ConfirmationDetails is attached to confirmation_required errors.
type ConfirmationDetails struct {
	Production  bool                    `json:"production"`
	Statements  []ConfirmStatement      `json:"statements"`
	Environment connections.Environment `json:"environment"`
	Connection  string                  `json:"connection"`
}

// ConfirmStatement is a statement that requires confirmation.
type ConfirmStatement struct {
	SQL    string          `json:"sql"`
	Kind   sqllex.Category `json:"kind"`
	Reason string          `json:"reason"`
}

// Plan selects the statements a request will run.
func Plan(req ExecuteRequest) ([]sqllex.Statement, error) {
	stmts := sqllex.Split(req.SQL)
	if len(stmts) == 0 {
		return nil, apperr.New(apperr.CodeValidation, "não há instrução SQL para executar")
	}
	switch req.Mode {
	case "script":
		return stmts, nil
	case "statement", "":
		if req.CursorOffset < 0 {
			return stmts, nil
		}
		st, ok := sqllex.StatementAt(stmts, req.CursorOffset)
		if !ok {
			return nil, apperr.New(apperr.CodeValidation, "não há instrução SQL na posição do cursor")
		}
		return []sqllex.Statement{st}, nil
	default:
		return nil, apperr.New(apperr.CodeValidation, "modo de execução inválido")
	}
}

// CheckPolicy enforces read-only profiles and confirmation of destructive
// statements or writes on production connections.
func CheckPolicy(p connections.Profile, stmts []sqllex.Statement, opts Options, confirmed bool) error {
	if p.ReadOnly {
		for _, st := range stmts {
			switch st.Kind {
			case sqllex.CatRead, sqllex.CatSession, sqllex.CatTransaction:
				if st.Kind == sqllex.CatSession && strings.HasPrefix(strings.ToUpper(strings.TrimSpace(st.Text)), "SET") && strings.Contains(strings.ToUpper(st.Text), "GLOBAL") {
					return apperr.New(apperr.CodeReadOnly, "a conexão está marcada como somente leitura; SET GLOBAL não é permitido")
				}
			default:
				return apperr.New(apperr.CodeReadOnly, "a conexão está marcada como somente leitura; a instrução \""+abbreviate(st.Text, 60)+"\" não é permitida")
			}
		}
	}
	if confirmed {
		return nil
	}
	prod := p.Environment == connections.EnvProduction
	var need []ConfirmStatement
	for _, st := range stmts {
		switch {
		case st.Destructive && (opts.ConfirmDestructive || prod):
			need = append(need, ConfirmStatement{SQL: abbreviate(st.Text, 400), Kind: st.Kind, Reason: st.Reason})
		case prod && st.Kind != sqllex.CatRead && st.Kind != sqllex.CatSession && st.Kind != sqllex.CatTransaction:
			need = append(need, ConfirmStatement{SQL: abbreviate(st.Text, 400), Kind: st.Kind, Reason: "alteração em conexão de produção"})
		}
	}
	if len(need) == 0 {
		return nil
	}
	e := apperr.New(apperr.CodeConfirmationRequired, "confirmação necessária antes de executar")
	e.Details = ConfirmationDetails{Production: prod, Statements: need, Environment: p.Environment, Connection: p.Name}
	return e
}

func abbreviate(s string, n int) string {
	r := []rune(strings.Join(strings.Fields(s), " "))
	if len(r) <= n {
		return string(r)
	}
	return string(r[:n]) + "…"
}

// Execute runs SQL for a tab. Database errors are reported per statement in
// the response; the returned error covers request-level problems.
func (s *Service) Execute(ctx context.Context, req ExecuteRequest) (*ExecuteResponse, error) {
	t, err := s.tab(req.TabID, true)
	if err != nil {
		return nil, err
	}
	sess, err := s.sessions.Get(req.ConnectionID)
	if err != nil {
		return nil, err
	}
	switch req.Source {
	case "":
		req.Source = SourceEditor
	case SourceEditor, SourceData:
	default:
		return nil, apperr.New(apperr.CodeValidation, "origem de execução inválida")
	}
	stmts, err := Plan(req)
	if err != nil {
		return nil, err
	}
	opts := s.options()
	if err := CheckPolicy(sess.Profile, stmts, opts, req.Confirmed); err != nil {
		return nil, err
	}
	if !t.busy.TryLock() {
		return nil, apperr.New(apperr.CodeBusy, "já existe uma execução em andamento nesta aba")
	}
	defer t.busy.Unlock()

	runCtx, cancel := context.WithCancel(context.Background())
	defer cancel()
	exec := &execution{id: newID(), cancel: cancel}
	resp := &ExecuteResponse{ExecutionID: exec.id}
	start := time.Now()

	// Leaving a previous cursor open would block the connection.
	s.discardCursor(t)

	conn, notice, err := s.ensureConn(ctx, t, sess)
	resp.Notice = notice
	if err != nil {
		return nil, err
	}
	if req.Database != "" && req.Database != t.getDatabase() {
		if cd, ok := sess.Driver.(database.CurrentDatabaser); ok {
			if err := cd.UseDatabase(ctx, conn, req.Database); err != nil {
				return nil, apperr.FromDB(sess.Driver.DescribeError(err))
			}
			t.setDatabase(req.Database)
		}
	}

	t.mu.Lock()
	t.running = exec
	t.mu.Unlock()
	defer func() {
		t.mu.Lock()
		t.running = nil
		t.lastUsed = time.Now()
		t.mu.Unlock()
	}()

	var timer *time.Timer
	if opts.Timeout > 0 {
		timer = time.AfterFunc(opts.Timeout, func() { s.cancelExecution(t, exec) })
		defer timer.Stop()
	}

	keepCursor := len(stmts) == 1
	profiler, _ := sess.Driver.(database.Profiler)
	var showProfile, disableProfile string
	if req.Profile && profiler != nil {
		var enable string
		enable, showProfile, disableProfile = profiler.ProfileSQL(len(stmts) > 1)
		if _, err := conn.ExecContext(runCtx, enable); err == nil {
			keepCursor = false
		} else {
			showProfile = ""
		}
	}
	warner, _ := sess.Driver.(database.Warner)
	clearWarnings := func(next int) {
		// Keep warnings for a following SHOW WARNINGS typed by the user.
		if next < len(stmts) && isDiagnostics(stmts[next].Text) {
			return
		}
		if rows, err := conn.QueryContext(runCtx, warner.ClearWarningsSQL()); err == nil {
			_ = rows.Close()
		}
	}
	if opts.Warnings && warner != nil && t.hadWarnings {
		clearWarnings(0)
		t.hadWarnings = false
	}
	for i, st := range stmts {
		if exec.isCancelled() {
			break
		}
		r := s.runStatement(runCtx, t, sess, conn, st, i, opts, keepCursor, req.Source)
		if opts.Warnings && warner != nil && r.Error == nil && i < maxWarningStatements && r.CursorID == "" && !isDiagnostics(st.Text) {
			if ws, err := warner.Warnings(runCtx, conn); err == nil && len(ws) > 0 {
				r.Warnings = ws
				if i+1 < len(stmts) {
					clearWarnings(i + 1)
				} else {
					t.hadWarnings = true
				}
			}
		}
		resp.Results = append(resp.Results, r)
		if r.Error != nil {
			if r.Error.Category == "network" || errors.Is(runCtx.Err(), context.Canceled) {
				s.dropConn(t)
				resp.Notice = "A conexão desta aba foi encerrada; transações abertas foram revertidas pelo servidor."
				t.mu.Lock()
				t.inTx = false
				t.mu.Unlock()
			}
			break
		}
	}
	if showProfile != "" && t.getConn() != nil {
		pr := StatementResult{Index: len(resp.Results), SQL: showProfile, Kind: sqllex.CatRead, Profile: true}
		if rows, err := conn.QueryContext(runCtx, showProfile); err == nil {
			if cur, err := newCursor(rows); err == nil {
				pr.Columns, pr.HasRows = cur.cols, true
				pr.Rows, _, _ = cur.fetch(1000, 0)
				cur.close()
			} else {
				_ = rows.Close()
			}
		}
		_, _ = conn.ExecContext(context.Background(), disableProfile)
		if pr.HasRows {
			resp.Results = append(resp.Results, pr)
		}
	}
	if timer != nil && !timer.Stop() && exec.isCancelled() {
		resp.Notice = strings.TrimSpace(resp.Notice + " Tempo limite de execução atingido.")
	}
	resp.Cancelled = exec.isCancelled()

	// Refresh the current database after USE. Never while a cursor is open:
	// the connection is busy streaming its result set.
	t.mu.Lock()
	hasCursor := t.cursor != nil
	t.mu.Unlock()
	if c := t.getConn(); c != nil && !hasCursor && changesDatabase(stmts) {
		if cd, ok := sess.Driver.(database.CurrentDatabaser); ok {
			qctx, qcancel := context.WithTimeout(context.Background(), 5*time.Second)
			if name, err := cd.CurrentDatabase(qctx, c); err == nil {
				t.setDatabase(name)
			}
			qcancel()
		}
	}
	t.mu.Lock()
	resp.Database = t.database
	resp.InTransaction = t.inTx
	t.mu.Unlock()
	resp.DurationMs = ms(time.Since(start))
	return resp, nil
}

func ms(d time.Duration) float64 { return float64(d.Microseconds()) / 1000 }

func (t *tabContext) getConn() *sql.Conn {
	t.mu.Lock()
	defer t.mu.Unlock()
	return t.conn
}

func (t *tabContext) getDatabase() string {
	t.mu.Lock()
	defer t.mu.Unlock()
	return t.database
}

func (t *tabContext) setDatabase(db string) {
	t.mu.Lock()
	t.database = db
	t.mu.Unlock()
}

// ensureConn returns the tab's pinned connection for sess, acquiring one if
// needed. Switching sessions releases the previous connection.
func (s *Service) ensureConn(ctx context.Context, t *tabContext, sess *connections.Session) (*sql.Conn, string, error) {
	notice := ""
	t.mu.Lock()
	if t.conn != nil && t.sessionID == sess.ID && t.sess == sess {
		c := t.conn
		t.mu.Unlock()
		return c, "", nil
	}
	old, hadTx := t.conn, t.inTx
	wantDB := ""
	if t.sessionID == sess.ID && t.sess == sess {
		wantDB = t.database // re-pin after an idle release or lost connection
	}
	t.conn, t.sess, t.sessionID, t.connID, t.inTx = nil, nil, "", 0, false
	t.mu.Unlock()
	if old != nil {
		_ = old.Close()
		if hadTx {
			notice = "A transação aberta na conexão anterior foi encerrada (revertida pelo servidor)."
		}
	}

	actx, cancel := context.WithTimeout(ctx, acquireTimeout)
	defer cancel()
	conn, err := sess.DB.Conn(actx)
	if err != nil {
		if errors.Is(err, context.DeadlineExceeded) {
			return nil, notice, apperr.New(apperr.CodeBusy, "todas as conexões do pool estão em uso; feche abas ou aguarde")
		}
		return nil, notice, apperr.FromDB(sess.Driver.DescribeError(err))
	}
	var id int64
	if c, ok := sess.Driver.(database.Canceller); ok {
		if id, err = c.ConnectionID(actx, conn); err != nil {
			_ = conn.Close()
			return nil, notice, apperr.FromDB(sess.Driver.DescribeError(err))
		}
	}
	dbName := sess.Profile.Database
	if cd, ok := sess.Driver.(database.CurrentDatabaser); ok {
		if wantDB != "" {
			if err := cd.UseDatabase(actx, conn, wantDB); err == nil {
				dbName = wantDB
			}
		} else if name, err := cd.CurrentDatabase(actx, conn); err == nil {
			dbName = name
		}
	}
	t.mu.Lock()
	t.conn, t.sess, t.sessionID, t.connID, t.database = conn, sess, sess.ID, id, dbName
	t.mu.Unlock()
	return conn, notice, nil
}

// dropConn discards the tab's connection (after it became unusable).
func (s *Service) dropConn(t *tabContext) {
	t.mu.Lock()
	c := t.conn
	t.conn, t.connID = nil, 0
	t.mu.Unlock()
	if c != nil {
		// A broken connection reports itself invalid and is discarded by
		// database/sql; a healthy one returns to the pool. Either way the tab
		// pins a fresh connection on its next run.
		_ = c.Close()
	}
}

func (s *Service) runStatement(ctx context.Context, t *tabContext, sess *connections.Session, conn *sql.Conn, st sqllex.Statement, idx int, opts Options, keepCursor bool, source string) StatementResult {
	r := StatementResult{Index: idx, SQL: st.Text, Line: st.Line, Kind: st.Kind}
	start := time.Now()
	ev := StatementEvent{ConnectionID: sess.ID, Database: t.getDatabase(), SQL: st.Text, Kind: st.Kind, At: start, Source: source}
	defer func() {
		r.DurationMs = ms(time.Since(start))
		if s.hooks.AfterStatement != nil {
			ev.Duration = time.Since(start)
			ev.Err = r.Error
			if r.RowsAffected != nil {
				ev.RowCount = *r.RowsAffected
			} else {
				ev.RowCount = int64(len(r.Rows))
			}
			s.hooks.AfterStatement(ev)
		}
	}()
	describe := func(err error) *database.DBError {
		de := *sess.Driver.DescribeError(err)
		de.Message = sess.Redact(de.Message)
		return &de
	}

	if returnsRows(st) {
		// The cursor gets its own context so it can outlive this execution;
		// until the first page is read it follows the execution's context.
		cctx, ccancel := context.WithCancel(context.Background())
		unlink := context.AfterFunc(ctx, ccancel)
		rows, err := conn.QueryContext(cctx, st.Text)
		if err != nil {
			unlink()
			ccancel()
			r.Error = describe(err)
			return r
		}
		cur, err := newCursor(rows)
		if err != nil {
			unlink()
			cur = &cursor{rows: rows, cancel: ccancel}
			cur.close()
			r.Error = describe(err)
			return r
		}
		cur.cancel = ccancel
		if len(cur.cols) == 0 {
			// Statement without a result set (e.g. CALL of a procedure
			// that only modifies data).
			unlink()
			cur.close()
			return r
		}
		r.HasRows = true
		r.Columns = cur.cols
		page, trunc, err := cur.fetch(opts.PageSize, 0)
		unlink()
		r.Rows, r.TruncatedCells = page, trunc
		if err != nil {
			cur.close()
			r.Error = describe(err)
			return r
		}
		r.HasMore = cur.hasMore
		r.LimitReached = cur.limitReached
		if cur.hasMore && keepCursor {
			cur.id = newID()
			cur.lastUsed = time.Now()
			t.mu.Lock()
			t.cursor = cur
			t.mu.Unlock()
			r.CursorID = cur.id
		} else if !cur.exhausted {
			s.closeUnfinished(t, sess, cur)
		} else {
			cur.close()
		}
		return r
	}

	res, err := conn.ExecContext(ctx, st.Text)
	if err != nil {
		r.Error = describe(err)
		return r
	}
	if n, err := res.RowsAffected(); err == nil {
		r.RowsAffected = &n
	}
	if id, err := res.LastInsertId(); err == nil && id != 0 {
		r.LastInsertID = &id
	}
	switch fx := sqllex.TransactionEffect(st.Text); {
	case fx > 0:
		t.mu.Lock()
		t.inTx = true
		t.mu.Unlock()
	case fx < 0:
		t.mu.Lock()
		t.inTx = false
		t.mu.Unlock()
	}
	return r
}

// isDiagnostics reports SHOW WARNINGS / SHOW ERRORS / SHOW COUNT(*) ... /
// GET DIAGNOSTICS, which read the diagnostics area.
func isDiagnostics(stmt string) bool {
	var words []string
	for _, tok := range sqllex.Tokenize(stmt) {
		if tok.Significant() {
			words = append(words, tok.Upper())
			if len(words) == 2 {
				break
			}
		}
	}
	if len(words) < 2 {
		return false
	}
	return words[0] == "GET" && (words[1] == "DIAGNOSTICS" || words[1] == "CURRENT" || words[1] == "STACKED") ||
		words[0] == "SHOW" && (words[1] == "WARNINGS" || words[1] == "ERRORS" || words[1] == "COUNT")
}

func changesDatabase(stmts []sqllex.Statement) bool {
	for _, st := range stmts {
		for _, tok := range sqllex.Tokenize(st.Text) {
			if tok.Significant() {
				if tok.IsKeyword("USE", "CALL") {
					return true
				}
				break
			}
		}
	}
	return false
}

// returnsRows decides whether to use Query (result set expected) or Exec.
func returnsRows(st sqllex.Statement) bool {
	if st.Kind == sqllex.CatRead {
		return true
	}
	head := ""
	returning := false
	for _, tok := range sqllex.Tokenize(st.Text) {
		if !tok.Significant() {
			continue
		}
		if head == "" {
			head = tok.Upper()
		}
		if tok.IsKeyword("RETURNING") {
			returning = true
		}
	}
	return head == "CALL" || returning
}

// FetchRequest asks for the next page of a cursor.
type FetchRequest struct {
	TabID    string `json:"tabId"`
	CursorID string `json:"cursorId"`
}

// FetchResponse is the next page of a cursor.
type FetchResponse struct {
	Rows           [][]any           `json:"rows"`
	HasMore        bool              `json:"hasMore"`
	LimitReached   bool              `json:"limitReached"`
	TruncatedCells [][2]int          `json:"truncatedCells,omitempty"`
	Offset         int               `json:"offset"`
	DurationMs     float64           `json:"durationMs"`
	Error          *database.DBError `json:"error,omitempty"`
}

// FetchMore reads the next page of the tab's open cursor.
func (s *Service) FetchMore(req FetchRequest) (*FetchResponse, error) {
	t, err := s.tab(req.TabID, false)
	if err != nil {
		return nil, err
	}
	if t == nil {
		return nil, apperr.New(apperr.CodeNotFound, "o resultado não está mais disponível")
	}
	if !t.busy.TryLock() {
		return nil, apperr.New(apperr.CodeBusy, "já existe uma execução em andamento nesta aba")
	}
	defer t.busy.Unlock()
	t.mu.Lock()
	cur, sess := t.cursor, t.sess
	t.mu.Unlock()
	if cur == nil || cur.id != req.CursorID {
		return nil, apperr.New(apperr.CodeNotFound, "o resultado não está mais disponível; execute a consulta novamente")
	}
	start := time.Now()
	offset := cur.fetched
	rows, trunc, err := cur.fetch(s.options().PageSize, offset)
	out := &FetchResponse{Rows: rows, TruncatedCells: trunc, Offset: offset, HasMore: cur.hasMore, LimitReached: cur.limitReached}
	if err != nil {
		de := *sess.Driver.DescribeError(err)
		de.Message = sess.Redact(de.Message)
		out.Error = &de
	}
	if !cur.hasMore || err != nil {
		t.mu.Lock()
		t.cursor = nil
		t.mu.Unlock()
		if !cur.exhausted {
			s.closeUnfinished(t, sess, cur)
		} else {
			cur.close()
		}
		out.HasMore = false
	} else {
		cur.lastUsed = time.Now()
	}
	t.mu.Lock()
	t.lastUsed = time.Now()
	t.mu.Unlock()
	out.DurationMs = ms(time.Since(start))
	return out, nil
}

// CloseCursor discards the tab's cursor (e.g. when the user dismisses a
// result).
func (s *Service) CloseCursor(tabID string) error {
	t, err := s.tab(tabID, false)
	if err != nil || t == nil {
		return err
	}
	if !t.busy.TryLock() {
		return nil // an execution will replace the cursor anyway
	}
	defer t.busy.Unlock()
	s.discardCursor(t)
	return nil
}

func (s *Service) discardCursor(t *tabContext) {
	t.mu.Lock()
	cur, sess := t.cursor, t.sess
	t.cursor = nil
	t.mu.Unlock()
	if cur == nil {
		return
	}
	s.closeUnfinished(t, sess, cur)
}

// closeUnfinished closes a result set that still has unread rows. Closing it
// normally would download every remaining row. Outside a transaction the
// connection is simply dropped (fast); inside a transaction the server is
// asked to stop sending (KILL QUERY) and the rest is drained so the
// transaction survives.
func (s *Service) closeUnfinished(t *tabContext, sess *connections.Session, cur *cursor) {
	t.mu.Lock()
	inTx, connID := t.inTx, t.connID
	t.mu.Unlock()
	if !inTx {
		cur.abort()
		s.dropConn(t)
		return
	}
	if c, ok := sess.Driver.(database.Canceller); ok && connID > 0 {
		ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		_ = c.CancelQuery(ctx, sess.DB, connID)
		cancel()
	}
	cur.close()
}

// Cancel stops the execution running in a tab.
func (s *Service) Cancel(tabID string) error {
	t, err := s.tab(tabID, false)
	if err != nil || t == nil {
		return err
	}
	t.mu.Lock()
	exec := t.running
	t.mu.Unlock()
	if exec == nil {
		return nil
	}
	s.cancelExecution(t, exec)
	return nil
}

// cancelExecution first asks the server to stop the statement (KILL QUERY),
// which keeps the connection and transaction; if the statement is still
// running after a grace period the client context is cancelled, which drops
// the connection.
func (s *Service) cancelExecution(t *tabContext, exec *execution) {
	if !exec.markCancelled() {
		return
	}
	t.mu.Lock()
	sess, connID := t.sess, t.connID
	t.mu.Unlock()
	if sess != nil && connID > 0 {
		if c, ok := sess.Driver.(database.Canceller); ok {
			ctx, cancel := context.WithTimeout(context.Background(), cancelGrace)
			err := c.CancelQuery(ctx, sess.DB, connID)
			cancel()
			if err == nil {
				time.AfterFunc(cancelGrace, func() {
					t.mu.Lock()
					still := t.running == exec
					t.mu.Unlock()
					if still {
						exec.cancel()
					}
				})
				return
			}
		}
	}
	exec.cancel()
}

// TabState reports a tab's execution context.
type TabState struct {
	TabID         string `json:"tabId"`
	ConnectionID  string `json:"connectionId"`
	Database      string `json:"database"`
	InTransaction bool   `json:"inTransaction"`
	Running       bool   `json:"running"`
	HasCursor     bool   `json:"hasCursor"`
}

// State returns the state of a tab.
func (s *Service) State(tabID string) (TabState, error) {
	t, err := s.tab(tabID, false)
	if err != nil {
		return TabState{}, err
	}
	if t == nil {
		return TabState{TabID: tabID}, nil
	}
	t.mu.Lock()
	defer t.mu.Unlock()
	return TabState{TabID: tabID, ConnectionID: t.sessionID, Database: t.database, InTransaction: t.inTx, Running: t.running != nil, HasCursor: t.cursor != nil}, nil
}

// ReleaseTab frees a tab's resources (on close or connection change). If a
// transaction is open and force is false, a confirmation error is returned.
func (s *Service) ReleaseTab(tabID string, force bool) error {
	t, err := s.tab(tabID, false)
	if err != nil || t == nil {
		return err
	}
	t.mu.Lock()
	inTx, exec := t.inTx, t.running
	t.mu.Unlock()
	if inTx && !force {
		return apperr.New(apperr.CodeConfirmationRequired, "a aba possui uma transação aberta que será revertida")
	}
	if exec != nil {
		s.cancelExecution(t, exec)
	}
	// Wait for the execution to finish (bounded by the cancel grace period).
	done := make(chan struct{})
	go func() { t.busy.Lock(); close(done) }()
	select {
	case <-done:
	case <-time.After(2 * cancelGrace):
		return apperr.New(apperr.CodeBusy, "a execução não terminou a tempo; tente novamente")
	}
	defer t.busy.Unlock()
	s.discardCursor(t)
	t.mu.Lock()
	c := t.conn
	t.conn, t.sess, t.sessionID, t.connID, t.inTx = nil, nil, "", 0, false
	t.mu.Unlock()
	if c != nil {
		_ = c.Close()
	}
	s.mu.Lock()
	delete(s.tabs, tabID)
	s.mu.Unlock()
	return nil
}

// releaseSession is called by the connection manager before closing a pool.
func (s *Service) releaseSession(sessionID string) {
	s.mu.Lock()
	var tabs []*tabContext
	for _, t := range s.tabs {
		t.mu.Lock()
		if t.sessionID == sessionID {
			tabs = append(tabs, t)
		}
		t.mu.Unlock()
	}
	s.mu.Unlock()
	var wg sync.WaitGroup
	for _, t := range tabs {
		wg.Add(1)
		go func(t *tabContext) {
			defer wg.Done()
			t.mu.Lock()
			exec := t.running
			t.mu.Unlock()
			if exec != nil {
				exec.markCancelled()
				exec.cancel()
			}
			done := make(chan struct{})
			go func() { t.busy.Lock(); close(done) }()
			select {
			case <-done:
				defer t.busy.Unlock()
			case <-time.After(2 * cancelGrace):
			}
			t.mu.Lock()
			cur, c := t.cursor, t.conn
			t.cursor, t.conn, t.sess, t.sessionID, t.connID, t.inTx = nil, nil, nil, "", 0, false
			t.mu.Unlock()
			if cur != nil {
				cur.close()
			}
			if c != nil {
				_ = c.Close()
			}
		}(t)
	}
	wg.Wait()
}

// janitor closes idle cursors and idle pinned connections.
func (s *Service) janitor() {
	defer s.wg.Done()
	tick := time.NewTicker(time.Minute)
	defer tick.Stop()
	for {
		select {
		case <-s.stop:
			return
		case <-tick.C:
			s.sweep(time.Now())
		}
	}
}

func (s *Service) sweep(now time.Time) {
	s.mu.Lock()
	tabs := make([]*tabContext, 0, len(s.tabs))
	for _, t := range s.tabs {
		tabs = append(tabs, t)
	}
	s.mu.Unlock()
	for _, t := range tabs {
		if !t.busy.TryLock() {
			continue
		}
		t.mu.Lock()
		cur := t.cursor
		idleCursor := cur != nil && now.Sub(cur.lastUsed) > CursorIdleTimeout
		idleConn := t.conn != nil && cur == nil && !t.inTx && now.Sub(t.lastUsed) > ConnIdleTimeout
		t.mu.Unlock()
		if idleCursor {
			s.discardCursor(t)
		}
		if idleConn {
			t.mu.Lock()
			c := t.conn
			t.conn, t.connID = nil, 0 // keep sess/database so the next run re-pins
			t.mu.Unlock()
			_ = c.Close()
		}
		t.busy.Unlock()
	}
}

// Close stops background work and releases every tab.
func (s *Service) Close() {
	select {
	case <-s.stop:
	default:
		close(s.stop)
	}
	s.wg.Wait()
	s.mu.Lock()
	ids := make([]string, 0, len(s.tabs))
	for id := range s.tabs {
		ids = append(ids, id)
	}
	s.mu.Unlock()
	for _, id := range ids {
		_ = s.ReleaseTab(id, true)
	}
}
