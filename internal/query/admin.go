package query

import (
	"context"
	"database/sql"
	"strings"
	"time"

	"dbstudio/internal/apperr"
	"dbstudio/internal/database"
	"dbstudio/internal/sqllex"
)

// adminTimeout bounds statements issued from dialogs and object actions.
const adminTimeout = 2 * time.Minute

// Statement sources reported in StatementEvent.Source.
const (
	SourceEditor = "editor" // typed by the user in a SQL tab
	SourceData   = "data"   // generated by the table data grid
	SourceApp    = "app"    // generated by dialogs and object actions
)

// AdminResult is the outcome of one statement run by RunAdmin.
type AdminResult struct {
	SQL          string            `json:"sql"`
	RowsAffected *int64            `json:"rowsAffected,omitempty"`
	LastInsertID *int64            `json:"lastInsertId,omitempty"`
	DurationMs   float64           `json:"durationMs"`
	Error        *database.DBError `json:"error,omitempty"`
}

// AdminRequest describes statements generated by the application (DDL from
// dialogs, DROP/TRUNCATE from the object tree, KILL, SET GLOBAL ...).
type AdminRequest struct {
	ConnectionID string
	// Database is selected with USE before running ("" keeps the default).
	Database   string
	Statements []string
	Confirmed  bool
	// ContinueOnError runs every statement even after a failure.
	ContinueOnError bool
	// DisableFKChecks runs the statements with FOREIGN_KEY_CHECKS=0 (dropping
	// or emptying tables that reference each other), restoring it afterwards.
	DisableFKChecks bool
	Timeout         time.Duration
	// Args holds the arguments of each statement (same index), if any.
	Args [][]any
	// Display holds each statement with its arguments rendered as literals;
	// used in confirmations and history instead of the "?" placeholders.
	Display []string
	// Transaction runs every statement in one transaction: the first error
	// rolls everything back.
	Transaction bool
	// MaxAffected > 0 fails (and, with Transaction, rolls back) a statement
	// that affects more rows than allowed, e.g. a grid edit matching
	// several rows.
	MaxAffected int64
}

// RunAdmin executes application-generated statements sequentially on one
// pooled connection. They go through the same policies as editor executions
// (read-only profiles, production and destructive confirmations) and the
// same history/metadata hooks. Database errors are reported per statement;
// the returned error covers request-level problems (policy, connection).
func (s *Service) RunAdmin(ctx context.Context, req AdminRequest) ([]AdminResult, error) {
	sess, err := s.sessions.Get(req.ConnectionID)
	if err != nil {
		return nil, err
	}
	// Every item is one statement built by the backend; it is not split
	// again because routine and trigger bodies contain semicolons. The
	// driver never runs multiple statements per call.
	var stmts []sqllex.Statement
	for _, text := range req.Statements {
		text = strings.TrimSpace(text)
		if text == "" {
			continue
		}
		st := sqllex.Statement{Text: text, End: len(text), Line: 1}
		st.Kind, st.Destructive, st.Reason = sqllex.Classify(text)
		stmts = append(stmts, st)
	}
	if len(stmts) == 0 {
		return nil, apperr.New(apperr.CodeValidation, "nenhuma instrução para executar")
	}
	policy := stmts
	if len(req.Display) == len(stmts) {
		policy = make([]sqllex.Statement, len(stmts))
		copy(policy, stmts)
		for i := range policy {
			policy[i].Text = req.Display[i]
		}
	}
	if err := CheckPolicy(sess.Profile, policy, s.options(), req.Confirmed); err != nil {
		return nil, err
	}
	timeout := req.Timeout
	if timeout <= 0 {
		timeout = adminTimeout
	}
	ctx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	conn, err := sess.DB.Conn(ctx)
	if err != nil {
		return nil, apperr.FromDB(sess.Driver.DescribeError(err))
	}
	defer conn.Close()
	if req.Database != "" {
		if cd, ok := sess.Driver.(database.CurrentDatabaser); ok {
			if err := cd.UseDatabase(ctx, conn, req.Database); err != nil {
				return nil, apperr.FromDB(sess.Driver.DescribeError(err))
			}
		}
	}
	if req.DisableFKChecks {
		if _, err := conn.ExecContext(ctx, "SET @OLD_FOREIGN_KEY_CHECKS = @@FOREIGN_KEY_CHECKS, FOREIGN_KEY_CHECKS = 0"); err != nil {
			return nil, apperr.FromDB(sess.Driver.DescribeError(err))
		}
		defer func() {
			_, _ = conn.ExecContext(context.Background(), "SET FOREIGN_KEY_CHECKS = @OLD_FOREIGN_KEY_CHECKS")
		}()
	}
	var execer interface {
		ExecContext(ctx context.Context, query string, args ...any) (sql.Result, error)
	} = conn
	var tx *sql.Tx
	if req.Transaction {
		if tx, err = conn.BeginTx(ctx, nil); err != nil {
			return nil, apperr.FromDB(sess.Driver.DescribeError(err))
		}
		execer = tx
		defer func() { _ = tx.Rollback() }() // no-op after Commit
	}
	out := make([]AdminResult, 0, len(stmts))
	failed := false
	for i, st := range stmts {
		var args []any
		if i < len(req.Args) {
			args = req.Args[i]
		}
		start := time.Now()
		res, err := execer.ExecContext(ctx, st.Text, args...)
		r := AdminResult{SQL: st.Text, DurationMs: ms(time.Since(start))}
		ev := StatementEvent{ConnectionID: req.ConnectionID, Database: req.Database, SQL: policy[i].Text, Kind: st.Kind, Duration: time.Since(start), At: start, Source: SourceApp}
		if err != nil {
			de := *sess.Driver.DescribeError(err)
			de.Message = sess.Redact(de.Message)
			r.Error, ev.Err = &de, &de
		} else {
			if n, err := res.RowsAffected(); err == nil {
				r.RowsAffected = &n
				ev.RowCount = n
				if req.MaxAffected > 0 && n > req.MaxAffected {
					r.Error = &database.DBError{Category: "constraint", Message: "a instrução afetaria mais linhas do que o permitido; nada foi gravado"}
					ev.Err = r.Error
				}
			}
			if id, err := res.LastInsertId(); err == nil && id != 0 {
				r.LastInsertID = &id
			}
		}
		if s.hooks.AfterStatement != nil {
			s.hooks.AfterStatement(ev)
		}
		out = append(out, r)
		if r.Error != nil {
			failed = true
			if req.Transaction || !req.ContinueOnError {
				break
			}
		}
	}
	if tx != nil && !failed {
		if err := tx.Commit(); err != nil {
			de := *sess.Driver.DescribeError(err)
			de.Message = sess.Redact(de.Message)
			out = append(out, AdminResult{SQL: "COMMIT", Error: &de})
		}
	}
	return out, nil
}

// RunDDL executes one statement generated by the application (e.g. CREATE
// TABLE from the table dialog) and returns its error as an apperr.Error.
func (s *Service) RunDDL(ctx context.Context, connectionID, stmt, database string, confirmed bool) error {
	res, err := s.RunAdmin(ctx, AdminRequest{ConnectionID: connectionID, Database: database, Statements: []string{stmt}, Confirmed: confirmed})
	if err != nil {
		return err
	}
	if res[0].Error != nil {
		return apperr.FromDB(res[0].Error)
	}
	return nil
}
